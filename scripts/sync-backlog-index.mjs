#!/usr/bin/env node
/**
 * Rewrite the issue index in the project's work document from the LIVE GitHub state.
 *
 * The index is a convenience mirror, and a mirror that is not refreshed lies:
 * it was generated once at seeding time, so the first closed issue would have
 * made it wrong. Run this whenever you open or close an issue (the issue-flow
 * skill says so) — it is idempotent and prints nothing to commit when nothing
 * changed.
 *
 *   node scripts/sync-backlog-index.mjs             # rewrite the block
 *   node scripts/sync-backlog-index.mjs --check     # exit 1 if stale (for CI)
 *
 * Requires: gh CLI authenticated with `repo` scope.
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Project specifics come from .dev-standards.json — see lib/config.mjs.
import { issueFlowConfig } from './lib/config.mjs';
const ROOT = process.cwd();
const CFG = issueFlowConfig(ROOT);
const BACKLOG = join(ROOT, CFG.workDocument);
const REPO = CFG.repo;
const CHECK = process.argv.includes('--check');

const BEGIN = '<!-- issue-index:begin — generated by scripts/sync-backlog-index.mjs, do not edit by hand -->';
const END = '<!-- issue-index:end -->';

const issues = JSON.parse(execFileSync('gh', [
  'issue', 'list', '-R', REPO, '--state', 'all', '--limit', '500',
  '--json', 'number,title,state,labels',
], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }));

// Slugs come from the manifest (they are the branch names, so the index is only
// useful with them). An issue opened through a GitHub form has no slug — it shows
// its number alone, which is enough to look it up.
let slugByTitle = new Map();
let reserve = [];
try {
  const manifest = JSON.parse(readFileSync(join(ROOT, CFG.manifest), 'utf8'));
  slugByTitle = new Map(manifest.issues.map((i) => [i.title, i.slug]));
  reserve = manifest.reserve || [];
} catch (_) { /* manifest optional */ }
const liveTitles = new Set();

const labelNames = (i) => i.labels.map((l) => l.name);
const trackOf = (i) => (labelNames(i).find((n) => n.startsWith('track/')) || '').split('/')[1] || 'untracked';
const prioOf = (i) => labelNames(i).find((n) => /^P[012]$/.test(n)) || 'P?';

const PRIO_ORDER = { P0: 0, P1: 1, P2: 2, 'P?': 3 };
const lines = [];
let open = 0, closed = 0;

// Lane order: whatever the project configured, then cross-lane, then unlabelled — so the
// index does not hard-code one project's lane names.
const laneOrder = [...Object.keys(CFG.owners), 'both', 'untracked']
  .filter((l, idx, all) => all.indexOf(l) === idx);
const lanes = [...new Set([...laneOrder, ...issues.map(trackOf)])];
for (const track of lanes) {
  const mine = issues.filter((i) => trackOf(i) === track);
  if (!mine.length) continue;
  mine.sort((a, b) => (PRIO_ORDER[prioOf(a)] - PRIO_ORDER[prioOf(b)]) || (a.number - b.number));
  const cells = mine.map((i) => {
    liveTitles.add(i.title);
    const done = i.state === 'CLOSED';
    done ? closed++ : open++;
    // A closed issue stays listed, struck through: the index doubles as the record
    // of what this backlog has actually shipped.
    const slug = slugByTitle.get(i.title);
    const label = `#${i.number} ${prioOf(i)}${slug ? ' ' + slug : ''}`;
    return done ? `~~${label}~~` : label;
  });
  const openCount = mine.filter((i) => i.state !== 'CLOSED').length;
  lines.push(`**${track}** (${openCount} open / ${mine.length})  ${cells.join(' · ')}`);
  lines.push('');
}

// The reserve: enumerated here so low-priority work is visible and countable instead of
// dissolving into the prose of the sections below.
const pending = reserve.filter((r) => !liveTitles.has(r.title));
const reserveLines = [];
if (pending.length) {
  reserveLines.push(`#### Reserve — ${pending.length} low-priority items, not yet issues`, '');
  reserveLines.push('_Promote one with `node scripts/seed-issues.mjs --only=<slug>` (then write its'
    + ` acceptance criteria and re-run this script). Detail: \`${CFG.manifest}\` → \`reserve\`._`, '');
  for (const track of lanes) {
    const mine = pending.filter((r) => r.track === track);
    if (!mine.length) continue;
    reserveLines.push(`**${track}** (${mine.length})  ${mine.map((r) => `${r.slug} \`${r.size}\``).join(' · ')}`, '');
  }
}

const block = [
  BEGIN,
  '',
  `_${open} open · ${closed} closed · ${pending.length} in the reserve · refreshed by `
    + '`node scripts/sync-backlog-index.mjs`. Titles and detail live on GitHub — `gh issue view <n>`._',
  '',
  ...lines,
  ...reserveLines,
  END,
].join('\n');

const src = readFileSync(BACKLOG, 'utf8');
let next;
if (src.includes(BEGIN) && src.includes(END)) {
  next = src.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), block);
} else {
  // First run after the static index: replace the hand-written list that follows
  // the "### Index" heading, up to the next horizontal rule.
  const heading = '### Index — issue number, priority, slug';
  const at = src.indexOf(heading);
  if (at < 0) {
    console.error(`Could not find "${heading}" in ${CFG.workDocument} — add the markers by hand:\n${BEGIN}\n${END}`);
    process.exit(1);
  }
  const restAt = src.indexOf('\n---', at);
  next = src.slice(0, at) + '### Index — issues by track\n\n' + block + '\n' + src.slice(restAt);
}

if (next === src) {
  console.log(`Index already current (${open} open, ${closed} closed).`);
  process.exit(0);
}
if (CHECK) {
  console.error('issue index is STALE — run: node scripts/sync-backlog-index.mjs');
  process.exit(1);
}
writeFileSync(BACKLOG, next);
console.log(`${CFG.workDocument} index updated — ${open} open, ${closed} closed.`);
